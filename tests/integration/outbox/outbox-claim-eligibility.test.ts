async function toUncorroboratedStall(at: Date): Promise<void> {
  await declareMirrorDegraded(h.control, COMPANY_ID, 'PUSH_ACK_TIMEOUT', at);
  expect((await evaluateState(h.control, COMPANY_ID, at)).state).toBe('UNCORROBORATED_STALL');
}

async function toCorroboratedDegraded(at: Date): Promise<void> {
  await declareMirrorDegraded(h.control, COMPANY_ID, 'PUSH_ACK_TIMEOUT', at);
  const signal = signalSignedWith(
    signalFieldsAt(at, { signalId: `signal:s1i-${String(at.getTime())}` }),
    h.auditKey.privateKey,
    signalSigningBytes,
  );
  const outcome = await consumeCorroboration(
    h.control,
    COMPANY_ID,
    signal,
    h.auditKey.publicKey,
    at,
  );
  expect(outcome.kind).toBe('SIGNAL_CONSUMED');
  expect((await evaluateState(h.control, COMPANY_ID, at)).state).toBe('CORROBORATED_DEGRADED');
}

async function enterState(state: OracleState, at: Date): Promise<void> {
  if (state === 'NORMAL') return;
  if (state === 'UNCORROBORATED_STALL') {
    await toUncorroboratedStall(at);
    return;
  }
  await toCorroboratedDegraded(at);
}

async function enqueue(effect: AuthorisedEffect, tag: string): Promise<void> {
  const outcome = await enqueueDispatch(h.control, {
    companyId: COMPANY_ID,
    effectId: effect.effectId,
    outboxId: `outbox:${tag}`,
    payloadCanonicalBytes: effect.payloadCanonicalBytes,
    now: T0,
  });
  expect(outcome.kind).toBe('ENQUEUED');
}

/** The claim's outcome, reduced to the oracle's own vocabulary. */
async function claimDisposition(
  effect: AuthorisedEffect,
  at: Date,
): Promise<{ readonly disposition: string; readonly row: number | null; readonly tag: boolean | null }> {
  const result = await claimForExternalDispatch(h.control, {
    companyId: COMPANY_ID,
    idempotencyKey: effect.idempotencyKey,
    claimedBy: WORKER,
    now: at,
  });
  if (result.kind === 'CLAIMED') {
    return {
      disposition: 'DISPATCH_ELIGIBLE',
      row: result.claim.matchedRow,
      tag: result.claim.requiresUnmirroredTag,
    };
  }
  const mapped =
    result.reason === 'PRE_DISPATCH_HALTED'
      ? 'HALT'
      : result.reason === 'PRE_DISPATCH_SUSPENDED'
        ? 'SUSPEND'
        : result.reason;
  return {
    disposition: mapped,
    row: result.decision?.matchedRow ?? null,
    tag: result.decision?.requiresUnmirroredTag ?? null,
  };
}

