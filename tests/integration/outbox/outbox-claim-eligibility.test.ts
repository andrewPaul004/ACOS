/**
 * `§13`, `§14`, `§15`, `§16`, `§33` — ELIGIBILITY IS DECIDED AT CLAIM TIME, FROM CURRENT
 * AUTHORITATIVE STATE.
 *
 * =================================================================================
 * THE RULE THE CLAIM OBEYS, VERBATIM (`30 §5.1` item 3's ordering block):
 *
 *   COMMIT  →  push to audit store  →  "dispatch, per (4)"
 *
 * Item 4 is the ordered first-match precedence list, and the CLAIM is the first durable
 * step of "dispatch". So item 4 is evaluated HERE, in the claim transaction, over operands
 * read there — not at enqueue, and never from a value a caller stored.
 *
 * `§13`: "An outbox row existing does NOT mean it can still be claimed. Mirror state, owner
 * override, statutory clock state, approval state or another current pre-dispatch operand
 * can change between enqueue and claim."
 *
 * THE OUTBOX TABLE HAS NO ELIGIBILITY COLUMN. `0010` adds none, deliberately, so `§14`'s
 * attack — an implementation trusting `eligible_at_enqueue = true` — has no field to trust.
 * The vulnerable control that carries one is `unsafe-stale-eligibility.ts`, and it is
 * TEST-ONLY.
 * =================================================================================
 *
 * =================================================================================
 * THE EXPECTATIONS COME FROM THE HAND-AUTHORED ORACLE.
 *
 * `mirrorPrecedenceTable.ts` transcribes `22 §3.1` and `30 §5.1` item 4 by hand and imports
 * nothing from `src/`. Every disposition asserted below is `expectedFor` /
 * `expectedUnderFullHalt`'s answer, never `classifyDispatchPrecedence`'s — `36 §0`'s rule
 * about self-validating tests, and `§39` of the S1H mandate in its own words: "Forbidden:
 * expected precedence generated by production rule list."
 *
 * `clockBearing` IS FALSE FOR EVERY CASE, and that is `S1I-C1` rather than a choice.
 * v1.3.3 declares no binding from an effect to a `statutory_clock.case_ref`, so the claim
 * reads the operand in the fail-closed direction and row 3 is unreachable at claim time.
 * `claim.ts`'s `clockBearingAtClaim` carries the full argument and `S1I-result.md §9`
 * reports the leg PARTIAL.
 * =================================================================================
 */

